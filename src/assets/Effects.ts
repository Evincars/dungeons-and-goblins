export type EffectShape = keyof typeof EFFECT_SHAPES;

const FRAME = 64;
/** Ticks each effect frame shows. */
const EFFECT_FRAME_TICKS = 3;

export function effectSheetKey(shape: EffectShape): string {
  return `fx_${shape}`;
}

/** Registers every effect sheet to load on first use. */
export function registerEffects(): void {
  for (const [shape, [part, file]] of Object.entries(EFFECT_SHAPES)) {
    const key = `fx_${shape}`;
    registerLazy(new SpriteSheet(key, `/effects/Part ${part}/${file}.png`, { grid: { frameWidth: FRAME, frameHeight: FRAME } }), [key]);
  }
}

/**
 * Plays an effect once at (x, y), `lift` pixels above the ground, loading its sheet first if this is the
 * first time; `scale` sizes it (frames are 64 px).
 */
export function playEffect(shape: EffectShape, colour: EffectColour, x: number, y: number, lift = 0, scale = 1): void {
  const key = effectSheetKey(shape);
  const frames = EFFECT_SHAPES[shape][2];
  const row = EFFECT_COLOURS.indexOf(colour);
  const spawn = (): Entity => spawnFx(x, y, key, frames, frames * EFFECT_FRAME_TICKS, { row, yOffset: lift, scale });
  reportRejection(requestArt(key).then(spawn), `Effect ${shape} did not load`, 'render');
}
